# generates engine/src/script/intl/date_patterns_data.rs, the date and time patterns and names
# Intl.DateTimeFormat formats with, from the CLDR in Microsoft Edge itself
#
#     python -I engine/tools/date_patterns.py <output .rs file> [path to msedge.exe]
#
# date_patterns.html runs in a headless Edge: for every option set V8 can be given it formats
# sample times to parts and turns the parts back into the CLDR pattern behind them, and it
# reads month, weekday, era, day period and zone names the same way; strings shared between
# locales are stored once

