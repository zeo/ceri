import json
import os
import re
import subprocess
import sys
import urllib.parse
import urllib.request

LOCALES = [
    "en-US", "en-GB", "en-AU", "en-CA", "en-IN", "en-IE", "en-NZ", "en-ZA", "en-SG",
    "de-DE", "de-AT", "de-CH", "fr-FR", "fr-CA", "fr-CH", "fr-BE", "es-ES", "es-MX", "es-419",
    "es-AR", "es-CO", "es-US", "it-IT", "it-CH", "pt-BR", "pt-PT", "nl-NL", "nl-BE", "ru-RU",
    "uk-UA", "pl-PL", "cs-CZ", "sk-SK", "sv-SE", "da-DK", "nb-NO", "fi-FI", "hu-HU", "ro-RO",
    "bg-BG", "hr-HR", "sr-RS", "sl-SI", "el-GR", "tr-TR", "he-IL", "ar-EG", "ar-SA", "fa-IR",
    "hi-IN", "bn-BD", "th-TH", "vi-VN", "id-ID", "ms-MY", "ja-JP", "ko-KR", "zh-CN", "zh-TW",
    "zh-HK", "lt-LT", "lv-LV", "et-EE", "ca-ES", "fil-PH", "ur-PK", "ta-IN", "kk-KZ",
]

ZONES = [
    "America/New_York", "America/Chicago", "America/Denver", "America/Phoenix",
    "America/Los_Angeles", "America/Anchorage", "Pacific/Honolulu", "America/Toronto",
    "America/Vancouver", "America/Mexico_City", "America/Sao_Paulo", "America/Halifax",
    "America/St_Johns", "Europe/London", "Europe/Dublin", "Europe/Lisbon", "Europe/Paris",
    "Europe/Berlin", "Europe/Madrid", "Europe/Rome", "Europe/Amsterdam", "Europe/Warsaw",
    "Europe/Kyiv", "Europe/Athens", "Europe/Istanbul", "Europe/Moscow", "Asia/Dubai",
    "Asia/Kolkata", "Asia/Shanghai", "Asia/Hong_Kong", "Asia/Tokyo", "Asia/Seoul",
    "Asia/Singapore", "Asia/Jakarta", "Australia/Sydney", "Australia/Perth",
    "Australia/Adelaide", "Pacific/Auckland", "Africa/Johannesburg", "Africa/Cairo", "UTC",
]

DATE_SKELETONS = 4 * 3 * 6 * 3
TIME_SKELETONS = 5 * 3 * 3 * 7
# dates, times, glue, the default hour, date and time styles, months, weekdays, day periods,
# eras, digits, the GMT format and the zone names, as the runtime reads them
ROW = DATE_SKELETONS + TIME_SKELETONS + 4 + 1 + 4 + 4 + 72 + 56 + 2 + 4 + 1 + 10 + len(ZONES) * 8


def edge_path(given):
    if given:
        return given
    for root in [os.environ.get("ProgramFiles(x86)"), os.environ.get("ProgramFiles")]:
        if root:
            candidate = os.path.join(root, "Microsoft", "Edge", "Application", "msedge.exe")
            if os.path.exists(candidate):
                return candidate
    raise RuntimeError("msedge.exe was not found; pass its path")


def extract(edge, locales):
    page = os.path.abspath(os.path.join(os.path.dirname(__file__), "date_patterns.html"))
    url = urllib.parse.urljoin("file:", urllib.request.pathname2url(page))
    url += "#" + urllib.parse.quote(json.dumps(locales))
    output = subprocess.run(
        [edge, "--headless", "--disable-gpu", "--virtual-time-budget=60000", "--dump-dom", url],
        capture_output=True, check=True, timeout=600,
    ).stdout.decode("utf-8")
    found = re.search(r'<pre id="out">(.*?)</pre>', output, re.S)
    if not found or not found.group(1):
        raise RuntimeError("the extraction page wrote nothing")
    return json.loads(html.unescape(found.group(1)))


def rust_string(text):
    escaped = []
    for character in text:
        if character in '\\"':
            escaped.append("\\" + character)
        elif ord(character) < 32:
            escaped.append(f"\\u{{{ord(character):x}}}")
        else:
            escaped.append(character)
    return '"' + "".join(escaped) + '"'


def main(output, edge=None):
    edge = edge_path(edge)
    rows = {}
    for start in range(0, len(LOCALES), 12):
        rows.update(extract(edge, LOCALES[start : start + 12]))
    table, positions = [], {}

    def intern(text):
        if text not in positions:
            positions[text] = len(table)
            table.append(text)
        return positions[text]

    lines = [
        "// date and time patterns and names for Intl.DateTimeFormat from the CLDR in Microsoft Edge;",
        "// generated by engine/tools/date_patterns.py, regenerate instead of editing",
        "",
        f"pub(super) const DATE_SKELETONS: usize = {DATE_SKELETONS};",
        f"pub(super) const TIME_SKELETONS: usize = {TIME_SKELETONS};",
        f"pub(super) const PATTERN_ZONES: &[&str] = &[{', '.join(rust_string(zone) for zone in ZONES)}];",
        "",
    ]
    entries = []
    for tag in LOCALES:
        values = rows[tag]
        if len(values) != ROW:
            raise RuntimeError(f"{tag} has {len(values)} strings, not {ROW}")
        entries.append(f'    ("{tag}", &[{", ".join(str(intern(value)) for value in values)}]),')
    lines += [
        "// every string, each once, separated by U+001F",
        "pub(super) const STRINGS: &str = " + rust_string("\x1f".join(table)) + ";",
        "",
        "// per locale, the index of each of its strings in the order date_patterns.rs reads them",
        "pub(super) const DATE_LOCALES: &[(&str, &[u16])] = &[",
        *entries,
        "];",
        "",
    ]
    with open(output, "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(lines))
    print(f"{len(entries)} locales, {len(table)} strings")


if __name__ == "__main__":
    main(*sys.argv[1:])
